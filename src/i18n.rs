pub fn get(lang: &str) -> &'static Strings {
    match lang {
        "ar" => &AR,
        "it" => &IT,
        "fr" => &FR,
        "es" => &ES,
        "de" => &DE,
        "ru" => &RU,
        "hi" => &HI,
        "tr" => &TR,
        "pt" => &PT,
        _ => &EN,
    }
}

